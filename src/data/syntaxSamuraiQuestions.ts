/**
 * Filter questions by language and difficulty
 */
export function getQuestionsByFilter(
  language: LanguageEnemy,
  difficulty: Difficulty
): SyntaxQuestion[] {
  return SYNTAX_QUESTIONS.filter(
    (q) => q.language === language && q.difficulty === difficulty
  );
}

/**
 * Select a pseudo-randomized or sliced set of questions for a battle session
 */
export function getRandomQuestions(
  language: LanguageEnemy,
  difficulty: Difficulty,
  count?: number
): SyntaxQuestion[] {
  const pool = getQuestionsByFilter(language, difficulty);
  const targetCount = count ?? DIFFICULTY_TIERS[difficulty].questionCount;
  
  // Deterministic shuffle copy
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(targetCount, shuffled.length));
}

